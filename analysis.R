args <- commandArgs(trailingOnly=TRUE)
script <- grep('^--file=', commandArgs(), value=TRUE)
base <- if(length(script)) dirname(normalizePath(sub('^--file=', '', script[1]))) else getwd()
d <- read.csv(file.path(base,'data.csv'))
stopifnot(all(c('YEAR','JAN','FEB','MAR','APR','MAY','JUN','JUL','AUG','SEP','OCT','NOV','DEC') %in% names(d)))
months <- names(d)[-1]
d$annual_mean <- rowMeans(d[,months], na.rm=TRUE)
fit <- lm(annual_mean ~ YEAR, data=d)
test <- t.test(d$annual_mean[d$YEAR < 1980], d$annual_mean[d$YEAR >= 1980])
write.csv(data.frame(year=d$YEAR,annual_mean=d$annual_mean),file.path(base,'annual_means.csv'),row.names=FALSE)
png(file.path(base,'enso_trend.png'),width=1200,height=650)
plot(d$YEAR,d$annual_mean,type='l',lwd=2,xlab='Year',ylab='Mean sea-surface temperature (°C)',main='Historical El Niño region sea-surface temperatures')
abline(fit,col='red',lty=2,lwd=2)
dev.off()
cat('Slope (°C/year):',coef(fit)[2],'\nWelch two-sample p-value:',test$p.value,'\n')
writeLines(c(capture.output(summary(fit)),capture.output(test)),file.path(base,'results.txt'))
